"""Parity tests: `site/stats.py` vs the legacy `src/utils/statistics.ts`.

Expectations come from `tests/golden_stats.json`, which is generated by running
the fixtures through the *original* TypeScript implementation
(`tests/golden/generate_golden.mjs`).  Nothing in this file is derived from the
Python port, so a regression in either engine shows up here.
"""

from __future__ import annotations

import math
import unittest

import stats
from _helpers import GoldenTestCase, numbers_equal


class ColumnStatsParityTest(GoldenTestCase):
    def assertStatsMatch(self, fixture_name: str, column: str) -> None:
        rows = self.golden["fixtures"][fixture_name]
        expected = self.golden["columnStats"][fixture_name][column]
        actual = stats.calculate_column_stats(rows, column)

        self.assertEqual(
            set(actual),
            set(expected),
            f"{fixture_name}.{column}: key mismatch python={sorted(actual)} legacy={sorted(expected)}",
        )
        for key, value in expected.items():
            self.assertMatchesGolden(f"{fixture_name}.{column}.{key}", actual[key], value)

    def test_sales_fixture_columns(self) -> None:
        for column in self.golden["columnStats"]["sales"]:
            with self.subTest(column=column):
                self.assertStatsMatch("sales", column)

    def test_edge_fixture_columns(self) -> None:
        for column in self.golden["columnStats"]["edge"]:
            with self.subTest(column=column):
                self.assertStatsMatch("edge", column)

    def test_numeric_column_detection(self) -> None:
        rows = self.golden["fixtures"]["sales"]
        columns = list(rows[0])
        expected = [
            column
            for column in columns
            if self.golden["columnStats"]["sales"][column]["type"]
            in ("numeric", "mixed", "boolean")
        ]
        # numericColumnsFor keeps columns with at least one numeric cell.
        self.assertEqual(stats.numeric_columns(rows, columns), ["id", "sales", "quantity", "price", "rating"])
        self.assertIn("sales", expected)

    def test_dataset_summary(self) -> None:
        rows = self.golden["fixtures"]["sales"]
        columns = list(rows[0])
        summary = stats.dataset_summary(rows, columns)

        self.assertEqual(summary["totalRows"], len(rows))
        self.assertEqual(summary["totalColumns"], len(columns))
        self.assertEqual(summary["numericColumns"] + summary["categoricalColumns"], len(columns))
        self.assertEqual(summary["numericColumns"], 5)
        self.assertEqual(summary["missingValues"], 0)
        self.assertEqual(summary["missingPercent"], "0.00")


class FunctionParityTest(GoldenTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.rows = self.golden["fixtures"]["sales"]
        self.sales = [row["sales"] for row in self.rows]
        self.quantity = [row["quantity"] for row in self.rows]
        self.expected = self.golden["functions"]

    def test_descriptive_statistics(self) -> None:
        cases = {
            "mean": stats.mean(self.sales),
            "median": stats.median(self.sales),
            "mode": stats.mode(self.sales),
            "variance": stats.variance(self.sales),
            "stdDev": stats.std_dev(self.sales),
            "q1": stats.quartile(self.sales, 0.25),
            "q3": stats.quartile(self.sales, 0.75),
            "skewness": stats.skewness(self.sales),
            "kurtosis": stats.kurtosis(self.sales),
        }
        for name, actual in cases.items():
            with self.subTest(function=name):
                self.assertMatchesGolden(name, actual, self.expected[name])

    def test_probability_helpers(self) -> None:
        cases = {
            "probability": stats.probability(3, 8),
            "probabilityZeroTotal": stats.probability(3, 0),
            "factorial10": stats.factorial(10),
            "factorial171": stats.factorial(171),
            "combinations_10_3": stats.combinations(10, 3),
            "combinations_5_9": stats.combinations(5, 9),
            "permutations_10_3": stats.permutations(10, 3),
        }
        for name, actual in cases.items():
            with self.subTest(function=name):
                self.assertMatchesGolden(name, actual, self.expected[name])

    def test_factorial_overflow_matches_js_double(self) -> None:
        self.assertTrue(math.isinf(stats.factorial(171)))
        self.assertEqual(stats.factorial(170), 7.257415615307994e306)

    def test_distributions(self) -> None:
        cases = {
            "binomial_10_5_0p5": stats.binomial_probability(10, 5, 0.5),
            "binomial_20_7_0p3": stats.binomial_probability(20, 7, 0.3),
            "poisson_5_3": stats.poisson_probability(5, 3),
            "poisson_2p5_0": stats.poisson_probability(2.5, 0),
            "normalPDF_0_0_1": stats.normal_pdf(0, 0, 1),
            "normalPDF_90_80_5": stats.normal_pdf(90, 80, 5),
            "zScore_90_80_5": stats.z_score(90, 80, 5),
            "zScoreZeroStd": stats.z_score(5, 5, 0),
        }
        for name, actual in cases.items():
            with self.subTest(function=name):
                self.assertMatchesGolden(name, actual, self.expected[name])

    def test_correlation_helpers(self) -> None:
        cases = {
            "correlation_sales_qty": stats.correlation(self.sales, self.quantity),
            "covariance_sales_qty": stats.covariance(self.sales, self.quantity),
            "correlationMismatched": stats.correlation([1, 2, 3], [1, 2]),
            "correlationConstant": stats.correlation([1, 1, 1], [1, 2, 3]),
        }
        for name, actual in cases.items():
            with self.subTest(function=name):
                self.assertMatchesGolden(name, actual, self.expected[name])


class EdgeCaseParityTest(GoldenTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.expected = self.golden["edgeCases"]

    def test_empty_inputs(self) -> None:
        cases = {
            "meanEmpty": stats.mean([]),
            "medianEmpty": stats.median([]),
            "varianceEmpty": stats.variance([]),
            # `legacy.mode([])` returns undefined, which JSON drops entirely.
            "modeEmpty": stats.mode([]),
        }
        for name, actual in cases.items():
            with self.subTest(case=name):
                self.assertMatchesGolden(name, actual, self.expected.get(name))

    def test_median_and_mode_rules(self) -> None:
        cases = {
            "medianEven": stats.median([1, 2, 3, 4]),
            "medianOdd": stats.median([5, 1, 3]),
            "modeTieFirstWins": stats.mode(["b", "a", "b", "a"]),
            "modeNumericStrings": stats.mode(["2", "2", "3"]),
        }
        for name, actual in cases.items():
            with self.subTest(case=name):
                self.assertMatchesGolden(name, actual, self.expected[name])

    def test_small_sample_and_zero_dispersion_guards(self) -> None:
        cases = {
            "skewnessTooSmall": stats.skewness([1, 2]),
            "kurtosisTooSmall": stats.kurtosis([1, 2, 3]),
            "skewnessZeroStd": stats.skewness([4, 4, 4, 4]),
            "kurtosisZeroStd": stats.kurtosis([4, 4, 4, 4, 4]),
            "quartileSingle": stats.quartile([9], 0.75),
        }
        for name, actual in cases.items():
            with self.subTest(case=name):
                self.assertMatchesGolden(name, actual, self.expected[name])

    def test_column_type_detection(self) -> None:
        cases = {
            "columnTypeEmpty": stats.get_column_type([None, ""]),
            "columnTypeNumericStrings": stats.get_column_type(["1", "2.5"]),
            "columnTypeMixed": stats.get_column_type(["1", "abc"]),
            "columnTypeBoolean": stats.get_column_type([True, False]),
        }
        for name, actual in cases.items():
            with self.subTest(case=name):
                self.assertEqual(actual, self.expected[name], name)

    def test_whole_column_edge_cases(self) -> None:
        cases = {
            "statsEmptyColumn": stats.calculate_column_stats([{"a": None}, {"a": ""}], "a"),
            "statsSingleRow": stats.calculate_column_stats([{"a": 5}], "a"),
        }
        for name, actual in cases.items():
            expected = self.expected[name]
            with self.subTest(case=name):
                self.assertEqual(set(actual), set(expected), f"{name}: key mismatch")
                for key, value in expected.items():
                    self.assertMatchesGolden(f"{name}.{key}", actual[key], value)

    def test_missing_value_detection(self) -> None:
        self.assertTrue(stats.is_missing(None))
        self.assertTrue(stats.is_missing(""))
        self.assertFalse(stats.is_missing(0))
        self.assertFalse(stats.is_missing(False))
        self.assertFalse(stats.is_missing("0"))

    def test_numeric_coercion_matches_js_number(self) -> None:
        self.assertEqual(stats.to_number("12.5"), 12.5)
        self.assertIsNone(stats.to_number("not-a-number"))
        self.assertIsNone(stats.to_number(""))
        self.assertIsNone(stats.to_number(None))
        self.assertEqual(stats.to_number(True), 1.0)
        self.assertTrue(numbers_equal(stats.to_number("1e3"), 1000))


if __name__ == "__main__":
    unittest.main()
